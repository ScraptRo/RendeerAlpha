import rda
from state import State, Commands, define    # generated by `rda build . --python`

config = rda.StartupConfig()
config.name = "@NAME@"
config.theme = "res/themes/app.rdth"

# What commands.report() in the layout does. At module level this runs at import,
# before the engine exists; the binding remembers it and applies it once on_start has
# declared the names.
@Commands.report
def on_report():
    print("count:", State.count)

@config.on_start
def opened():
    define()                                  # the names, before the layout
    rda.load_interface("res/layouts/main.rdab", "res/layouts/main.tsx")

rda.init(config)
rda.wait()
