class StartupConfig:
    """What the engine needs to start.

    The callbacks are decorators as well as attributes, because a handler reads better
    where it is written than in an assignment three lines further down:

        @config.on_start
        def opened():
            ...
    """

    __slots__ = ("name", "theme", "languages", "vsync", "font", "font_height",
                 "_on_start", "_on_update", "_on_shutdown")

    def __init__(self):
        self.name = "RendeerAlpha"
        self.theme = ""       # a compiled .rdth; empty keeps the built-in look
        self.languages = ""   # res/themes/languages.xml, for syntax highlighting
        self.vsync = True
        self.font = ""        # a .ttf; empty keeps the engine's own
        self.font_height = 0  # pixels for body text; 0 keeps the default
        self._on_start = None
        self._on_update = None
        self._on_shutdown = None

    def on_start(self, fn):
        """Once, after the window is up. Load the interface here."""
        self._on_start = fn
        return fn

    def on_update(self, fn):
        """Once per frame, before it is drawn. Takes the seconds since the last one."""
        self._on_update = fn
        return fn

    def on_shutdown(self, fn):
        """Once, after the loop ends."""
        self._on_shutdown = fn
        return fn


_config_handle = None


def init(config=None):
    """Starts the engine and returns once it is up.

    Up means the window, the renderer and your on_start have all finished -- so the line
    after this one may write state and expect it to exist. The engine itself runs on a
    thread of its own, which is why this returns at all.

    Raises RdaError if it did not start, or if on_start stopped it.
    """
    global _config_handle
    from . import _engine

    lib = _engine.load()
    config = config or StartupConfig()

    handle = lib.rda_config_new()
    if not handle:
        raise RdaError("cannot allocate a config")
    lib.rda_config_set_name(handle, str(config.name).encode("utf-8"))
    if config.theme:
        lib.rda_config_set_theme(handle, str(config.theme).encode("utf-8"))
    if config.languages:
        lib.rda_config_set_languages(handle, str(config.languages).encode("utf-8"))
    lib.rda_config_set_vsync(handle, 1 if config.vsync else 0)
    if config.font or config.font_height:
        lib.rda_config_set_font(handle, str(config.font).encode("utf-8"),
                                float(config.font_height))

    # Held for the life of the process for the same reason a command handler is: the
    # engine calls these long after this function has returned.
    # on_start is always registered, whether or not the application wanted one: it is
    # also where handlers bound at import time are applied, and they can only be applied
    # after the application has declared the commands they name.
    def _started(_user):
        if config._on_start:
            config._on_start()
        _engine.flush_pending()

    trampoline = _engine._Callback(_started)
    _engine._alive.append(trampoline)
    lib.rda_config_on_start(handle, trampoline, None)
    if config._on_update:
        trampoline = _engine._UpdateCallback(lambda dt, _user: config._on_update(dt))
        _engine._alive.append(trampoline)
        lib.rda_config_on_update(handle, trampoline, None)
    if config._on_shutdown:
        trampoline = _engine._Callback(lambda _user: config._on_shutdown())
        _engine._alive.append(trampoline)
        lib.rda_config_on_shutdown(handle, trampoline, None)

    if not lib.rda_init(handle):
        lib.rda_config_free(handle)
        _engine._fail("the engine did not start")
    # Freed only after a successful start: rda_init copies what it needs, and freeing it
    # on the failure path above is what stops a refused start leaking one.
    lib.rda_config_free(handle)
    _config_handle = None


def load_interface(blueprint, source=""):
    """Shows a compiled layout (.rdab), replacing whatever was showing.

    `source` is the .tsx it came from. Where the build can compile one, naming it is what
    lets the engine reload the interface when the file changes.
    """
    from . import _engine
    lib = _engine.load()
    if not lib.rda_load_interface(str(blueprint).encode("utf-8"),
                                  str(source).encode("utf-8")):
        _engine._fail("cannot load {!r}".format(blueprint))


def open_routes(routes, layout_dir, source_dir=""):
    """Shows a set of screens, one at a time, with `state.route` naming which.

    `routes` is the ROUTES table a generated state module exports -- a mapping of name to
    {"layout": ..., "params": (...)}, in the order they were declared, because the first
    one is where the application opens unless `state.route` already says otherwise.

    After this, navigating is an ordinary write::

        State.route = "catalogue"

    which is the same sentence the interface itself uses, because "which screen is
    showing" is state and this engine has one answer for state.
    """
    import ctypes
    from . import _engine

    lib = _engine.load()
    names, layouts, params = [], [], []
    for name, route in routes.items():
        names.append(str(name).encode("utf-8"))
        if isinstance(route, str):        # {"home": "hello"}, the short spelling
            layouts.append(route.encode("utf-8"))
            params.append(b"")
        else:
            layouts.append(str(route["layout"]).encode("utf-8"))
            params.append(",".join(route.get("params") or ()).encode("utf-8"))
    if not names:
        raise RdaError("no routes to open")

    count = len(names)
    block = ctypes.c_char_p * count
    if not lib.rda_open_routes(block(*names), block(*layouts), block(*params), count,
                               str(layout_dir).encode("utf-8"),
                               str(source_dir).encode("utf-8")):
        _engine._fail("cannot open the screens")


