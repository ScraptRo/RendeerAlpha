def set_theme(path):
    """Swaps the whole look while the window stays open.

    The compiled `.rdth` replaces what was there rather than layering on top, so a theme
    that does not mention a variant does not inherit the last one's. Colours and radii
    travel to their new values over the transitionMs the new theme gives them; a theme
    whose variants say 0 swaps instantly.
    """
    if not _engine.load().rda_set_theme(str(path).encode("utf-8")):
        _engine._fail("cannot use the theme '{}'".format(path))


def _color(value):
    """A colour as the engine packs them: 0xAABBGGRR.

    Accepts what a theme accepts -- "#RGB", "#RRGGBB", "#RRGGBBAA" -- so a drawing and
    the interface around it can be written in the same notation. An int passes through,
    already packed.
    """
    if isinstance(value, int):
        return value & 0xFFFFFFFF
    text = str(value).lstrip("#")
    if len(text) == 3:
        text = "".join(c * 2 for c in text)
    if len(text) == 6:
        text += "FF"
    if len(text) != 8:
        raise RdaError("a colour is #RGB, #RRGGBB or #RRGGBBAA, not {!r}".format(value))
    r, g, b, a = (int(text[i:i + 2], 16) for i in (0, 2, 4, 6))
    return r | (g << 8) | (b << 16) | (a << 24)


class Drawing:
    """What to draw in a <viewport>, in its own coordinates: 0,0 is its top-left corner.

    Built up here and sent in one call, because every call into the engine crosses to its
    loop thread and waits -- a shape at a time would be a frame at a time. The list stays
    on screen until another one replaces it, so a drawing that does not change is drawn
    once and then costs nothing.

        d = rda.Drawing()
        d.clear("#11141A")
        for i, value in enumerate(values):
            d.rect(i * 12, height - value, 8, value, "#3A6AD0", radius=2)
        rda.draw("chart", d)
    """

    def __init__(self):
        self._commands = []

    def __len__(self):
        return len(self._commands)

    def clear(self, color):
        """Fills the whole viewport, whatever size it turned out to be."""
        self._add(_engine.DRAW_CLEAR, color)
        return self

    def rect(self, x, y, w, h, color, radius=0.0):
        self._add(_engine.DRAW_RECT, color, x, y, w, h, radius)
        return self

    def circle(self, x, y, radius, color):
        """A rect with equal sides and a radius of half of them. Centred on x, y."""
        self._add(_engine.DRAW_RECT, color, x - radius, y - radius,
                  radius * 2, radius * 2, radius)
        return self

    def line(self, x1, y1, x2, y2, color, width=1.0):
        self._add(_engine.DRAW_LINE, color, x1, y1, x2, y2, width)
        return self

    def text(self, x, y, text, color, size=0.0):
        """Top-left at x, y. A size of 0 is the interface's own, and the sizes that draw
        crisply are the ones the atlas was baked with."""
        self._add(_engine.DRAW_TEXT, color, x, y, 0.0, 0.0, size, text)
        return self

    def _add(self, op, color, a=0.0, b=0.0, c=0.0, d=0.0, e=0.0, text=None):
        command = _engine.DrawCmd()
        command.op = op
        command.color = _color(color)
        command.a, command.b, command.c, command.d, command.e = (
            float(a), float(b), float(c), float(d), float(e))
        if text is not None:
            # Kept alive on the command: ctypes stores the pointer, and the engine copies
            # it on the other side, but the bytes have to survive until it does.
            command._keep = str(text).encode("utf-8")
            command.text = command._keep
        self._commands.append(command)


def draw(name, drawing):
    """Puts `drawing` in the <viewport name="..."> and leaves it there.

    An empty Drawing takes it back down; a viewport nothing has ever drawn into shows the
    engine's own 3D scene instead, which is what this element used to be for.
    """
    commands = getattr(drawing, "_commands", None)
    if commands is None:
        raise TypeError("draw() takes a Drawing")
    count = len(commands)
    block = (_engine.DrawCmd * count)(*commands) if count else None
    if not _engine.load().rda_viewport_draw(name.encode("utf-8"), block, count):
        _engine._fail("cannot draw in '{}'".format(name))


def viewport_size(name="main"):
    """(width, height) in the pixels a drawing uses, or (0, 0) before a frame placed it."""
    from ctypes import byref, c_float
    width, height = c_float(0.0), c_float(0.0)
    if not _engine.load().rda_viewport_size(name.encode("utf-8"), byref(width), byref(height)):
        _engine._fail("cannot measure '{}'".format(name))
    return width.value, height.value
